// 🤖 Generates the tour's data and zips into _tour/, for /tour/.
//
// The tour's lessons and code live in the framework repo, where a test
// replays every step and proves it builds. Its tourgen command writes
// what this site needs, the same way dsgen writes the design-system
// gallery (see hack/gen-design-system.mjs):
//
//   go run amadan.net/rastrillo/rastrillo/cmd/tourgen@<sha> -out _tour
//
// which leaves _tour/tour.json and _tour/zips/<name>.zip. The sha is
// the one in src/_data/docsversion.json, so the tour, the docs and the
// gallery always describe the same framework commit.
//
// src/_data/tour.js reads _tour/tour.json to render the pages, and
// eleventy.config.js copies _tour/zips/ to /tour/zips/. _tour/ is
// gitignored: it is build output, like _site/.
//
// --from DIR (or TOUR_FROM=DIR in the environment) copies an
// already-generated directory instead of running Go. It is for working
// on the pages: test/fixtures/tour is a small hand-made tour for that,
// and any real tourgen output directory works too. The receipt records
// which it was, and hack/check-tour.mjs says so when it passes, so a
// build from a fixture cannot pass for a real one.
//
// Usage:
//   node hack/gen-tour.mjs
//   node hack/gen-tour.mjs --from test/fixtures/tour
//   node hack/gen-tour.mjs --out DIR
import { execFileSync } from "node:child_process";
import {
  copyFileSync,
  mkdirSync,
  readFileSync,
  readdirSync,
  rmSync,
  statSync,
  writeFileSync,
} from "node:fs";
import { join, resolve } from "node:path";
import { validateTour } from "./tour-schema.mjs";

const MODULE = "amadan.net/rastrillo/rastrillo/cmd/tourgen";
const DEFAULT_OUT = "_tour";
// Written after the tour has landed in the output directory, so
// hack/check-tour.mjs can tell a fresh tour from a leftover one and say
// where it came from. Read back by that name.
const RECEIPT = ".tourgen-source.json";

const args = process.argv.slice(2);
const flag = (name) => {
  const at = args.indexOf(name);
  if (at === -1) return undefined;
  const value = args[at + 1];
  if (!value || value.startsWith("--")) {
    console.error("usage: node hack/gen-tour.mjs [--from DIR] [--out DIR]");
    process.exit(2);
  }
  return value;
};
const out = flag("--out") ?? DEFAULT_OUT;
const from = flag("--from") ?? (process.env.TOUR_FROM || undefined);

if (from && resolve(from) === resolve(out)) {
  console.error(`--from and --out are the same directory (${out})`);
  process.exit(2);
}

// Clear only what this script or tourgen puts here, never the whole
// directory: --out may name somewhere that holds other things.
for (const name of ["tour.json", "zips", RECEIPT]) {
  rmSync(join(out, name), { recursive: true, force: true });
}
mkdirSync(out, { recursive: true });

let receipt;
if (from) {
  try {
    statSync(join(from, "tour.json"));
  } catch {
    console.error(`--from ${from}: there is no tour.json in that directory`);
    process.exit(1);
  }
  console.log(`copying the tour from ${from} (not running tourgen) …`);
  copyFileSync(join(from, "tour.json"), join(out, "tour.json"));
  mkdirSync(join(out, "zips"), { recursive: true });
  let zips = [];
  try {
    zips = readdirSync(join(from, "zips"));
  } catch {
    // No zips directory: validation below names every missing zip.
  }
  for (const name of zips) {
    copyFileSync(join(from, "zips", name), join(out, "zips", name));
  }
  receipt = { from };
} else {
  const { sha, short } = JSON.parse(readFileSync("src/_data/docsversion.json", "utf8"));
  if (!/^[0-9a-f]{40}$/.test(sha ?? "")) {
    console.error(`src/_data/docsversion.json has no usable sha (${JSON.stringify(sha)})`);
    console.error("run: node hack/sync-docs.mjs <path-to-rastrillo-checkout>");
    process.exit(1);
  }
  try {
    execFileSync("go", ["version"], { stdio: "ignore" });
  } catch {
    console.error("no `go` on PATH — the tour is generated by the framework's");
    console.error("tourgen command and the site cannot be built without it.");
    console.error("Install Go 1.25 or newer: https://go.dev/dl/");
    console.error("To work on the pages without Go, use a generated directory:");
    console.error("  TOUR_FROM=test/fixtures/tour npm run build");
    process.exit(1);
  }
  const spec = `${MODULE}@${sha}`;
  console.log(`generating the tour from ${short ?? sha.slice(0, 7)} …`);
  try {
    execFileSync("go", ["run", spec, "-out", out], { stdio: "inherit" });
  } catch (err) {
    console.error(`\ngo run ${spec} failed (${err.status ?? err.message}).`);
    console.error("The tour is NOT generated; the site would publish without it.");
    process.exit(1);
  }
  receipt = { sha, short: short ?? sha.slice(0, 7), module: MODULE };
}

// Check the shape before Eleventy renders it: a field tourgen renamed
// should stop the build here with its name, not render as an empty
// page that nobody opens.
let tour;
try {
  tour = JSON.parse(readFileSync(join(out, "tour.json"), "utf8"));
} catch (err) {
  console.error(`${join(out, "tour.json")} is not readable JSON: ${err.message}`);
  process.exit(1);
}
const problems = validateTour(tour);
for (const step of tour.steps ?? []) {
  // A name the schema rejected is already reported; don't stat it.
  if (typeof step.zip !== "string" || /[\/\\]/.test(step.zip)) continue;
  try {
    statSync(join(out, "zips", step.zip));
  } catch {
    problems.push(`step ${step.number}: zips/${step.zip} is missing`);
  }
}
if (problems.length) {
  console.error(`${join(out, "tour.json")} does not match the tour.json schema:`);
  for (const p of problems) console.error(`  - ${p}`);
  process.exit(1);
}

writeFileSync(
  join(out, RECEIPT),
  JSON.stringify({ ...receipt, slug: tour.slug, steps: tour.steps.length }, null, 2) + "\n",
);
console.log(
  `tour: "${tour.title}", ${tour.steps.length} steps at ${out}, ` +
    (from ? `copied from ${from}` : `from ${receipt.short}`),
);
