// 🤖 Generates the Rastrillo components gallery into src/components/.
//
// The gallery (every partial and icon, in three themes and twelve
// languages) is about 40 MB of machine output. It used to be committed
// in the framework repo and vendored here byte for byte; it is now
// rendered on demand by the framework's own dsgen command, so this repo
// carries a sha instead of a tree:
//
//   go run amadan.net/rastrillo/rastrillo/cmd/dsgen@<sha> \
//       -out src/components -mount /components -redirect-from /design-system
//
// The sha is the one in src/_data/docsversion.json, the same commit
// hack/sync-docs.mjs vendored the prose from. Reading it from there
// rather than pinning a second version is the point: the gallery and
// the docs it sits beside can never describe different framework
// versions.
//
// The gallery lived at /design-system until Rastrillo v0.38.0 renamed it
// and moved it to /components. -redirect-from makes dsgen add a
// _redirects file to the output: a 301 for every address it published
// at the old mount, to the same file under /components or, for the
// tokens and UI primitives pages that left the gallery, to Fiesta. Its
// rules match whole site paths, so eleventy.config.js publishes it at
// the site root rather than inside /components.
//
// dsgen owns the output directory and empties it on every run, so this
// is idempotent and leaves no stale file behind. It takes about a
// second once Go has the module cached; there is deliberately no
// "already generated, skipping" path, because the failure this whole
// change has to avoid is a build that quietly ships no gallery.
//
// Usage:
//   node hack/gen-components.mjs
//   node hack/gen-components.mjs --out DIR    # somewhere else
import { execFileSync } from "node:child_process";
import { readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { join } from "node:path";

// The framework moved to amadan.net (rastrillo #140, 2026-09-01). The old
// github.com/carlosframework/rastrillo path cannot serve any sha from after
// that move: go verifies the module path against go.mod, and go.mod now
// reads amadan.net/rastrillo/rastrillo. Pinning a post-move sha with the old
// path fails to resolve rather than silently building something stale.
const MODULE = "amadan.net/rastrillo/rastrillo/cmd/dsgen";
// Every URL in the output is an absolute path under the mount, so this
// has to be the path the site serves the tree from. eleventy.config.js
// maps src/components to /components; the two must agree, and
// hack/check-docs.mjs checks that they do.
const MOUNT = "/components";
// Where the gallery used to be served. Every old address redirects.
const REDIRECT_FROM = "/design-system";
const DEFAULT_OUT = "src/components";
// dsgen's redirect rules, written into the output when -redirect-from
// is passed. eleventy.config.js and hack/check-docs.mjs use this name.
const REDIRECTS = "_redirects";
// Written after dsgen has run, so the check can tell a fresh gallery
// from a leftover one and say which sha it came from. dsgen empties the
// directory first, so this file cannot outlive its own render.
// hack/check-docs.mjs reads it back by this same name.
const RECEIPT = ".dsgen-source.json";

const args = process.argv.slice(2);
const outFlag = args.indexOf("--out");
const out = outFlag === -1 ? DEFAULT_OUT : args[outFlag + 1];
if (!out) {
  console.error("usage: node hack/gen-components.mjs [--out DIR]");
  process.exit(2);
}

const { sha, short } = JSON.parse(readFileSync("src/_data/docsversion.json", "utf8"));
if (!/^[0-9a-f]{40}$/.test(sha ?? "")) {
  console.error(`src/_data/docsversion.json has no usable sha (${JSON.stringify(sha)})`);
  console.error("run: node hack/sync-docs.mjs <path-to-rastrillo-checkout>");
  process.exit(1);
}

try {
  execFileSync("go", ["version"], { stdio: "ignore" });
} catch {
  console.error("no `go` on PATH: the components gallery is generated by the");
  console.error("framework's dsgen command and the site cannot be built without it.");
  console.error("Install Go 1.25 or newer: https://go.dev/dl/");
  process.exit(1);
}

const spec = `${MODULE}@${sha}`;
console.log(`generating the components gallery from ${short ?? sha.slice(0, 7)} …`);
try {
  execFileSync(
    "go",
    ["run", spec, "-out", out, "-mount", MOUNT, "-redirect-from", REDIRECT_FROM],
    { stdio: "inherit" },
  );
} catch (err) {
  console.error(`\ngo run ${spec} failed (${err.status ?? err.message}).`);
  console.error("The gallery is NOT generated; the site would publish without it.");
  process.exit(1);
}

// dsgen exits non-zero on a partial write, but a build that publishes
// an empty /components is the one failure this repo cannot see from
// the outside, so count what landed before believing it.
// Dotfiles are dsgen's own bookkeeping (.dsgen) and this script's
// (.dsgen-source.json), and _redirects is published at the site root;
// none of them is part of the gallery, and eleventy.config.js keeps
// them out of the built /components. Counting only what will be
// published there is what makes this number comparable with the one
// hack/check-docs.mjs finds in _site.
const count = (dir, top = true) => {
  let n = 0;
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    if (entry.name.startsWith(".")) continue;
    if (top && entry.name === REDIRECTS) continue;
    n += entry.isDirectory() ? count(join(dir, entry.name), false) : 1;
  }
  return n;
};
let files = 0;
try {
  files = count(out);
  statSync(join(out, "index.html"));
  statSync(join(out, REDIRECTS));
} catch (err) {
  console.error(`dsgen exited 0 but ${out} is not a gallery with redirects: ${err.message}`);
  process.exit(1);
}
if (files < 2) {
  console.error(`dsgen exited 0 but wrote only ${files} file(s) to ${out}`);
  process.exit(1);
}

writeFileSync(
  join(out, RECEIPT),
  JSON.stringify(
    {
      sha,
      short: short ?? sha.slice(0, 7),
      mount: MOUNT,
      redirectFrom: REDIRECT_FROM,
      module: MODULE,
      files,
    },
    null,
    2,
  ) + "\n",
);
console.log(
  `components: ${files} files at ${out}, from ${short ?? sha.slice(0, 7)}, ` +
    `mounted at ${MOUNT}, redirecting ${REDIRECT_FROM}`,
);
